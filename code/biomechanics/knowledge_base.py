def get_exercise_biomechanics(exercise_name: str) -> dict:
    """Return all biomechanical knowledge for an exercise.

    Args:
        exercise_name: Chinese exercise name (e.g. "深蹲", "俯卧撑").

    Returns:
        Dict of {error_name: biomechanics} for this exercise, or empty dict.
    """
    return BIOMECHANICS_KB.get(exercise_name, {})


def get_error_biomechanics(exercise_name: str, error_name: str) -> Optional[dict]:
    """Return biomechanical knowledge for a specific exercise + error combination.

    Args:
        exercise_name: Chinese exercise name.
        error_name: Chinese error name (must exactly match KB key).

    Returns:
        Dict with root_cause_chain, correction_cues, compensation_patterns,
        or None if not found.
    """
    exercise_kb = BIOMECHANICS_KB.get(exercise_name, {})
    return exercise_kb.get(error_name)


def format_biomechanics_for_prompt(exercise_name: str,
                                    error_names: list[str]) -> dict:
    """Build a biomechanics injection dict for the current exercise + errors.

    Only includes knowledge for errors that are actually detected, to
    minimise token usage.

    Args:
        exercise_name: Chinese exercise name.
        error_names: List of detected error names (Chinese).

    Returns:
        Dict {error_name: biomechanics} containing only detected errors'
        knowledge. Empty dict if exercise not in KB or no matching errors.
    """
    exercise_kb = BIOMECHANICS_KB.get(exercise_name, {})
    if not exercise_kb:
        return {}

    result = {}
    for err_name in error_names:
        kb = exercise_kb.get(err_name)
        if kb:
            result[err_name] = kb
    return result


def get_cooccurrence_interpretation(errors: list[str]) -> Optional[str]:
    """Look up biomechanical interpretation of a co-occurring error pair.

    Currently handles 2-error combinations. Returns a human-readable
    Chinese interpretation string or None.
    """
    if len(errors) < 2:
        return None

